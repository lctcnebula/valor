// Draws the Valor Limo car as calligraphic (broad-nib) strokes: thick on the uprights, hairline on the flats,
// like the italic of "Valor". Writes lib/car-paths.mjs. Run: node scripts/build-car.mjs
import { writeFileSync } from "node:fs";

// The car's centre line: a stretch limo. The road rises into the rear, a long low roof runs over "Valor", and it
// comes down over the hood and nose to the road. Front is on the right. Also the spark's path and the draw mask.
export const LINE =
  "M30 300 H112 C126 300 132 294 133 284 L134 244 C135 234 142 228 156 227 L206 224 C222 223 232 218 242 208 " +
  "L268 176 C276 166 288 161 304 161 L640 158 C658 158 670 163 682 172 L722 204 C730 211 742 215 758 216 " +
  "L818 221 C836 223 846 234 848 250 L849 284 C849 294 856 300 868 300 H930";
export const WHEELS = [{ cx: 196, cy: 270, r: 27 }, { cx: 782, cy: 270, r: 27 }];

/** Flattens M/H/L/C path data into points. */
function flatten(d) {
  const t = d.match(/[MHLC]|-?[\d.]+/g);
  const pts = [];
  let i = 0, x = 0, y = 0, cmd = "";
  const num = () => +t[i++];
  while (i < t.length) {
    if (/[MHLC]/.test(t[i])) cmd = t[i++];
    if (cmd === "M" || cmd === "L") { x = num(); y = num(); pts.push([x, y]); }
    else if (cmd === "H") { const x1 = num(); for (let k = 1; k <= 40; k++) pts.push([x + ((x1 - x) * k) / 40, y]); x = x1; }
    else if (cmd === "C") {
      const [x1, y1, x2, y2, x3, y3] = [num(), num(), num(), num(), num(), num()];
      for (let k = 1; k <= 60; k++) {
        const s = k / 60, u = 1 - s;
        pts.push([u * u * u * x + 3 * u * u * s * x1 + 3 * u * s * s * x2 + s * s * s * x3, u * u * u * y + 3 * u * u * s * y1 + 3 * u * s * s * y2 + s * s * s * y3]);
      }
      x = x3; y = y3;
    }
  }
  // L segments need subdividing too, so the width can vary along them
  const out = [pts[0]];
  for (let k = 1; k < pts.length; k++) {
    const [ax, ay] = out[out.length - 1], [bx, by] = pts[k];
    const n = Math.max(1, Math.ceil(Math.hypot(bx - ax, by - ay) / 3));
    for (let j = 1; j <= n; j++) out.push([ax + ((bx - ax) * j) / n, ay + ((by - ay) * j) / n]);
  }
  return out;
}

const arcPts = ({ cx, cy, r }, a0, a1) => {
  const n = Math.ceil(Math.abs(a1 - a0) / 2);
  return Array.from({ length: n + 1 }, (_, k) => {
    const a = ((a0 + ((a1 - a0) * k) / n) * Math.PI) / 180;
    return [cx + r * Math.cos(a), cy + r * Math.sin(a)];
  });
};

/** Outline of a broad-nib stroke along `pts`: width from wmin to wmax by direction, tapered at both ends. */
function nib(pts, { wmin, wmax, pen = 20, ends = 0.1, step = 2 }) {
  const pa = (pen * Math.PI) / 180;
  const len = [0];
  for (let k = 1; k < pts.length; k++) len.push(len[k - 1] + Math.hypot(pts[k][0] - pts[k - 1][0], pts[k][1] - pts[k - 1][1]));
  const L = len[len.length - 1], A = [], B = [];
  for (let k = 0; k < pts.length; k += step) {
    const p = pts[k], q0 = pts[Math.max(0, k - 1)], q1 = pts[Math.min(pts.length - 1, k + 1)];
    const th = Math.atan2(q1[1] - q0[1], q1[0] - q0[0]);
    let w = wmin + (wmax - wmin) * Math.abs(Math.sin(th - pa));
    const t = len[k] / L;
    if (t < ends) w *= Math.sin(((t / ends) * Math.PI) / 2);
    if (t > 1 - ends) w *= Math.sin((((1 - t) / ends) * Math.PI) / 2);
    const nx = -Math.sin(th), ny = Math.cos(th);
    A.push([p[0] + (nx * w) / 2, p[1] + (ny * w) / 2]);
    B.push([p[0] - (nx * w) / 2, p[1] - (ny * w) / 2]);
  }
  const f = (v) => +v.toFixed(1);
  return "M" + [...A, ...B.reverse()].map(([x, y]) => `${f(x)} ${f(y)}`).join("L") + "Z";
}

const body = nib(flatten(LINE), { wmin: 1, wmax: 6.2, step: 3 });
const wheels = WHEELS.map((w) => nib(arcPts(w, 215, 535), { wmin: 1, wmax: 4.6, ends: 0.18 }));

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(
    new URL("../lib/car-paths.mjs", import.meta.url),
    "// Generated by scripts/build-car.mjs: the car as calligraphic strokes. Do not edit by hand.\n" +
      `export const LINE = ${JSON.stringify(LINE)};\n` +
      `export const WHEELS = ${JSON.stringify(WHEELS)};\n` +
      `export const BODY = ${JSON.stringify(body)};\n` +
      `export const WHEEL_FILLS = ${JSON.stringify(wheels)};\n`,
  );
  console.log("body", body.length, "wheels", wheels.map((w) => w.length));
}
