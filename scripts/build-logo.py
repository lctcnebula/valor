"""Outlines the Valor Limo wordmark into lib/logo-paths.mjs, then the logo files are written by
scripts/export-logos.mjs (run both after a change):

  python3 scripts/build-logo.py <fonts dir>
  node scripts/export-logos.mjs

<fonts dir> holds CormorantGaramond-Italic.ttf (variable, github.com/google/fonts ofl/cormorantgaramond).
Needs fonttools and uharfbuzz (for kerning). "Valor" is outlined so the logo looks the same without the font."""
import json, os, sys
from io import BytesIO
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen
from fontTools.varLib.instancer import instantiateVariableFont

FONTS = sys.argv[1]
ROOT = os.path.join(os.path.dirname(__file__), "..")

font = instantiateVariableFont(TTFont(os.path.join(FONTS, "CormorantGaramond-Italic.ttf")), {"wght": 500})
buf = BytesIO(); font.save(buf)
hbfont = hb.Font(hb.Face(buf.getvalue()))
num = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")


def outline(text, size, tracking=0.0):
    """Kerned outline of `text` at `size` (plus `tracking` em between letters), baseline y=0, left ink edge x=0.
    Returns d, ink width, ink top (negative y)."""
    s = size / font["head"].unitsPerEm
    b = hb.Buffer(); b.add_str(text); b.guess_segment_properties()
    hb.shape(hbfont, b, {"kern": True})
    order, gs = font.getGlyphOrder(), font.getGlyphSet()
    placed, x = [], 0.0
    for info, pos in zip(b.glyph_infos, b.glyph_positions):
        placed.append((order[info.codepoint], x + pos.x_offset * s))
        x += pos.x_advance * s + tracking * size
    bp = BoundsPen(gs)
    for g, gx in placed:
        gs[g].draw(TransformPen(bp, (s, 0, 0, -s, gx, 0)))
    x0, y0, x1, y1 = bp.bounds
    pen = SVGPathPen(gs, ntos=num)
    for g, gx in placed:
        gs[g].draw(TransformPen(pen, (s, 0, 0, -s, gx - x0, 0)))
    return pen.getCommands(), round(x1 - x0, 2), round(y0, 2)


valor = outline("Valor", 128)
v = outline("V", 118)
# The logo: "Valor" with open letter spacing (0.16 em), the way it sits in the limo.
spaced = outline("Valor", 128, 0.16)
with open(os.path.join(ROOT, "lib", "logo-paths.mjs"), "w") as f:
    f.write("// Generated by scripts/build-logo.py: Cormorant Garamond Italic 500, outlined. Do not edit by hand.\n")
    f.write(f"export const VALOR = {json.dumps({'d': valor[0], 'w': valor[1], 'top': valor[2]})};\n")
    f.write(f"export const V = {json.dumps({'d': v[0], 'w': v[1], 'top': v[2]})};\n")
    f.write(f"export const VALOR_SPACED = {json.dumps({'d': spaced[0], 'w': spaced[1], 'top': spaced[2]})};\n")
print(json.dumps({"valor": valor[1:], "v": v[1:]}))
